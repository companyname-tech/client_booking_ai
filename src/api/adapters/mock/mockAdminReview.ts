import type { Campaign } from '@/types'
import type { AdminCampaignMeta, CampaignReviewData } from '@/types/admin'
import { hoursAgo, minutesAgo } from './time'

export function buildReviewData(campaign: Campaign, meta?: AdminCampaignMeta): CampaignReviewData {
  const id = campaign.id.replace('cmp_', '').toUpperCase().slice(0, 8)
  const displayId = `CAM-2026-${id.padStart(4, '0')}`
  const submittedAt = meta?.submittedAt ?? campaign.createdAt

  return {
    campaignId: campaign.id,
    displayId,
    submittedAt,
    aiReadiness: meta?.aiReadiness ?? 88,
    riskLevel: meta?.riskLevel ?? 'low',
    workflowStatus: meta?.workflowStatus ?? 'awaiting_approval',
    trainingStatus: meta?.trainingStatus ?? 'not_started',
    trainingScore: meta?.trainingScore,
    targetAssessment: {
      score: meta?.targetingScore ?? 92,
      summary: 'Targeting is specific enough for outbound prospecting.',
      strengths: ['Clear industry focus', 'Defined decision-maker titles', 'Geographic scope is actionable', 'Company size range is realistic'],
      issues: campaign.criteria.companySize.includes('500') ? ['Upper company size may reduce connect rates'] : [],
      recommendations: ['Consider narrowing to firms with active websites', 'Add secondary industry vertical for expansion'],
    },
    offerAnalysis: {
      clarity: 'Excellent',
      valueProposition: 'Strong',
      cta: 'Good',
      recommendation: 'Consider making the primary outcome more explicit in the opening pitch.',
    },
    budgetProjection: {
      monthlyBudget: campaign.budget.total,
      expectedLeads: Math.round(campaign.budget.total * 1.6),
      projectedConversations: Math.round(campaign.budget.total * 0.48),
      projectedBookingsMin: Math.round(campaign.budget.total * 0.048),
      projectedBookingsMax: Math.round(campaign.budget.total * 0.072),
      aiNote: 'Estimates based on similar campaigns in this vertical. Actual results may vary.',
    },
    agentConfig: {
      agentName: 'Avi',
      voice: 'Alloy',
      language: 'English',
      model: 'GPT-4o',
      role: 'Outbound booking specialist',
      objective: 'Qualify prospects and book strategy sessions',
      qualificationCriteria: ['Decision-maker confirmed', 'Active project or pain point', 'Budget authority or influence', 'Geographic fit'],
      bookingObjective: 'Schedule 30-minute strategy session via Calendly',
      fallbackBehavior: 'Offer to send case studies and schedule follow-up email',
    },
    complianceItems: [
      { id: 'c1', label: 'Targeting restrictions', status: 'passed' },
      { id: 'c2', label: 'Marketing consent', status: 'needs_review', note: 'Verify TCPA consent language' },
      { id: 'c3', label: 'Calling rules', status: 'passed' },
      { id: 'c4', label: 'Messaging rules', status: 'passed' },
      { id: 'c5', label: 'Recording disclosure', status: 'passed' },
      { id: 'c6', label: 'Data handling', status: 'passed' },
      { id: 'c7', label: 'Geographic restrictions', status: 'not_applicable' },
      { id: 'c8', label: 'Client-provided claims', status: 'needs_review', note: 'Review ROI claims in offer copy' },
      { id: 'c9', label: 'Offer accuracy', status: 'passed' },
    ],
    readinessChecklist: [
      { id: 'r1', label: 'Configuration', done: true, score: 96 },
      { id: 'r2', label: 'Targeting', done: true, score: meta?.targetingScore ?? 94 },
      { id: 'r3', label: 'Offer', done: true, score: meta?.offerScore ?? 92 },
      { id: 'r4', label: 'Booking', done: true, score: 100 },
      { id: 'r5', label: 'Integrations', done: campaign.status !== 'awaiting_ai_training', score: 88 },
      { id: 'r6', label: 'Compliance', done: false, score: meta?.complianceScore ?? 78 },
      { id: 'r7', label: 'Training', done: meta?.trainingStatus === 'trained', score: meta?.trainingScore },
    ],
    auditEvents: [
      { id: 'a1', timestamp: submittedAt, title: 'Campaign submitted by client', actor: 'client' },
      { id: 'a2', timestamp: minutesAgo(30), title: 'AI preliminary review completed', description: 'Readiness score calculated', actor: 'ai' },
      { id: 'a3', timestamp: minutesAgo(25), title: 'Compliance review started', actor: 'admin' },
      ...(meta?.trainingStatus === 'trained' ? [{ id: 'a4', timestamp: minutesAgo(10), title: 'AI training completed', actor: 'ai' as const }] : []),
    ],
    hasVideo: !['awaiting_ai_training', 'draft'].includes(campaign.status),
    videoMeta: { name: 'offer-vertical.mp4', size: '12.4 MB', orientation: 'Vertical' },
    bookingTitle: '{company} × {client} — {product}',
    bookingEmail: 'bookings@example.com',
    integrations: { gmail: 'Connected', calendly: 'Connected', zoom: 'Not connected' },
  }
}

